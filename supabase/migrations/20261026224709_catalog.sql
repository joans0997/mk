begin;
create table public.products (
  id bigint generated by default as identity primary key check (id > 0 and id <= 9007199254740991),
  name text not null check (length(trim(name)) between 1 and 180),
  category text not null default 'despensa' check (length(trim(category)) between 1 and 80),
  price numeric(12,2) not null check (price > 0 and price <= 1000000000),
  image_url text check (image_url is null or image_url ~ '^https://'),
  image_path text,
  is_offer boolean not null default false,
  is_best_seller boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index products_active_category_idx on public.products(active, category);
create function public.set_product_updated_at() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end;
$$;
create trigger products_updated_at before update on public.products for each row execute function public.set_product_updated_at();
alter table public.products enable row level security;
revoke all on public.products from anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update, delete on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;
create policy "Read active catalog" on public.products for select to anon, authenticated using (active = true);
-- app_metadata must be assigned server-side by the project owner; never use user_metadata for authorization.
create policy "Administrators manage catalog" on public.products for all to authenticated
using ((select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin')
with check ((select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin');
-- Create the public product-images bucket through Storage API/dashboard before uploading.
create policy "Administrators read image metadata" on storage.objects for select to authenticated
using (bucket_id = 'product-images' and (select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin');
create policy "Administrators upload images" on storage.objects for insert to authenticated
with check (bucket_id = 'product-images' and (select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin');
create policy "Administrators update images" on storage.objects for update to authenticated
using (bucket_id = 'product-images' and (select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin')
with check (bucket_id = 'product-images' and (select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin');
create policy "Administrators remove images" on storage.objects for delete to authenticated
using (bucket_id = 'product-images' and (select auth.jwt()->'app_metadata'->>'role') = 'catalog_admin');
commit;
